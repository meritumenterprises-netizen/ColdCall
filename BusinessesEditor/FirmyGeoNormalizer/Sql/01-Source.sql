SELECT Id,
 NULLIF(LTRIM(RTRIM(CONVERT(nvarchar(max),Detail_Powiat))),N'') COLLATE DATABASE_DEFAULT AS P,
 NULLIF(LTRIM(RTRIM(CONVERT(nvarchar(max),Detail_Gmina))),N'') COLLATE DATABASE_DEFAULT AS G,
 NULLIF(LTRIM(RTRIM(CONVERT(nvarchar(max),Detail_Miejscowosc))),N'') COLLATE DATABASE_DEFAULT AS M
INTO #Source FROM dbo.Firmy;
IF EXISTS(SELECT 1 FROM #Source WHERE Id IS NULL)
 OR EXISTS(SELECT Id FROM #Source GROUP BY Id HAVING COUNT_BIG(*)>1)
 THROW 51003,N'Kolumna dbo.Firmy.Id musi jednoznacznie identyfikować każdy rekord i nie może być NULL.',1;
IF EXISTS(SELECT 1 FROM #Source WHERE DATALENGTH(P)>400 OR DATALENGTH(G)>400 OR DATALENGTH(M)>400)
 THROW 51004,N'Zbyt długie nazwy: powiat/gmina/miejscowość max. 200 jednostek UTF-16. Migracja nie obcina danych.',1;
ALTER TABLE #Source ALTER COLUMN P nvarchar(200) COLLATE DATABASE_DEFAULT NULL;
ALTER TABLE #Source ALTER COLUMN G nvarchar(200) COLLATE DATABASE_DEFAULT NULL;
ALTER TABLE #Source ALTER COLUMN M nvarchar(200) COLLATE DATABASE_DEFAULT NULL;
CREATE UNIQUE CLUSTERED INDEX IX_GeoSource_Id ON #Source(Id);
