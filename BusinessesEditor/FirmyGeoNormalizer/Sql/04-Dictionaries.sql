INSERT dbo.Powiat(Nazwa)
SELECT DISTINCT s.P FROM #Source s WHERE s.P IS NOT NULL AND NOT EXISTS(SELECT 1 FROM dbo.Powiat p WHERE p.Nazwa=s.P);
SELECT @@ROWCOUNT AS NowePowiaty;
