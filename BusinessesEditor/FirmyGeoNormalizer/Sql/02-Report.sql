SELECT COUNT_BIG(*) AS LiczbaFirm,COUNT_BIG(P) AS FirmyZPowiatem,COUNT_BIG(G) AS FirmyZGmina,COUNT_BIG(M) AS FirmyZMiejscowoscia FROM #Source;
SELECT N'Powiat' AS Slownik,COUNT_BIG(*) AS UnikalneNazwy FROM (SELECT DISTINCT P FROM #Source WHERE P IS NOT NULL) x
UNION ALL SELECT N'Gmina',COUNT_BIG(*) FROM (SELECT DISTINCT G FROM #Source WHERE G IS NOT NULL) x
UNION ALL SELECT N'Miejscowosc',COUNT_BIG(*) FROM (SELECT DISTINCT M FROM #Source WHERE M IS NOT NULL) x;
